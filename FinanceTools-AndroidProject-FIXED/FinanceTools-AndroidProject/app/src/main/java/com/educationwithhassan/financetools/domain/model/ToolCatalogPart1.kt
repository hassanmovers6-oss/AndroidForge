internal fun fCurr(key: String, label: String, def: String) =
    ToolField(key, label, InputKind.CURRENCY, def)

internal fun fNum(key: String, label: String, def: String, optional: Boolean = false) =
    ToolField(key, label, InputKind.NUMBER, def, optional = optional)

internal fun fPct(key: String, label: String, def: String) =
    ToolField(key, label, InputKind.PERCENT, def)

internal fun fTxt(key: String, label: String, def: String) =
    ToolField(key, label, InputKind.TEXT, def)

internal fun fDate(key: String, label: String, def: String) =
    ToolField(key, label, InputKind.DATE, def)

internal fun fSel(key: String, label: String, def: String, opts: List<Pair<String, String>>) =
    ToolField(key, label, InputKind.SELECT, def, opts.map { SelectOption(it.first, it.second) })

